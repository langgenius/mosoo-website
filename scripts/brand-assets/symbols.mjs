// Culm segment symbols for the Session-as-culm diagram, drawn from the mark's
// geometry (see NODE in bamboo.mjs). Width is 100 units; colours come from the
// referencing element: fill/stroke default to currentColor and can be set per
// <use> with --culm-fill, --culm-ring, --culm-stroke and --culm-dash.

import { NODE } from "./bamboo.mjs";

const f = (v) => Number(v.toFixed(2)).toString();

/** The mark's internode outline at width 100 and height h (sides pinched by NODE.waist). */
export function internodePath(h) {
  const w = NODE.waist * 100;
  const c1x = NODE.c1[0] * w;
  const y1 = NODE.c1[1] * h;
  const y2 = NODE.c2[1] * h;
  const mid = h / 2;
  return [
    `M100 0H0`,
    `C${f(c1x)} ${f(y1)} ${f(w)} ${f(y2)} ${f(w)} ${f(mid)}`,
    `S${f(c1x)} ${f(h - y1)} 0 ${f(h)}`,
    `H100`,
    `C${f(100 - c1x)} ${f(h - y1)} ${f(100 - w)} ${f(h - y2)} ${f(100 - w)} ${f(mid)}`,
    `S${f(100 - c1x)} ${f(y1)} 100 0Z`,
  ].join("");
}

export function culmSymbols() {
  const inter = NODE.internode * 100; // 79.51: the mark's own proportion
  const gap = NODE.gap * 100; // 10.44
  const ring = NODE.band * 100; // 10.05
  const total = inter + gap + ring + gap; // trailing gap lets segments stack edge to edge
  const solid = 'style="fill:var(--culm-fill,currentColor)"';
  const ringFill = 'style="fill:var(--culm-ring,var(--culm-fill,currentColor))"';
  const dashed =
    'fill="none" vector-effect="non-scaling-stroke" style="stroke:var(--culm-stroke,currentColor);stroke-width:var(--culm-stroke-width,1.25px);stroke-dasharray:var(--culm-dash,4px 3px)"';
  const ringY = inter + gap;
  const sprite = `<svg xmlns="http://www.w3.org/2000/svg">
<!-- mosoo bamboo culm symbols. Geometry: apps/landing/public/brand/brand-mark.svg (internode ${f(inter)} : gap ${f(gap)} : ring ${f(ring)} per 100 width). Generated by scripts/brand-assets/generate.mjs. -->
<symbol id="culm-segment" viewBox="0 0 100 ${f(total)}">
<path ${solid} d="${internodePath(inter)}"/>
<rect ${ringFill} y="${f(ringY)}" width="100" height="${f(ring)}"/>
</symbol>
<symbol id="culm-segment-reclaimed" viewBox="0 0 100 ${f(total)}" overflow="visible">
<path ${dashed} d="${internodePath(inter)}"/>
<rect ${dashed} y="${f(ringY)}" width="100" height="${f(ring)}"/>
</symbol>
<symbol id="culm-internode" viewBox="0 0 100 100" preserveAspectRatio="none">
<path ${solid} d="${internodePath(100)}"/>
</symbol>
<symbol id="culm-internode-reclaimed" viewBox="0 0 100 100" preserveAspectRatio="none" overflow="visible">
<path ${dashed} d="${internodePath(100)}"/>
</symbol>
<symbol id="culm-ring" viewBox="0 0 100 ${f(ring)}" preserveAspectRatio="none">
<rect ${ringFill} width="100" height="${f(ring)}"/>
</symbol>
</svg>
`;
  return { "bamboo-culm.svg": sprite };
}
