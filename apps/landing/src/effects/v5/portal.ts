// Portal (v5 graft of v4c's scroll motion; owner 10-20: 「滚动的动效我觉得是有说法的」), declared with [data-portal].
// A sticky host whose ground is seen through the mosoo mark: closed, the window is the whole mark, its block (the
// concave-sided window of the logo outline) with the bar's line under it; with the scroll it opens until it covers
// the host and is taken away.
//
// Reverse-engineered from:
// - Enter Pro's door mask (staging refs/enter-pro/notes.md §3 row 4; cdp2/cssom-rules.json): `.anything-scene` is a
//   full-size layer over a 455vh + 100vh sticky stage, masked with portal.svg, and the mask's size and position are
//   scrubbed until the door covers the screen.
// - v4c (redesign/v4c apps/landing/src/effects/stage.ts): the same block path redrawn at every size (not scaled), so
//   the 1 px outline stays one pixel, the mark's line under it, a calm surface inside the closed window (v4c's grain
//   rings), and the clip taken away once the block covers the stage.
// What the door must not do (round 3a, staging v5/round3/door/NOTES.md): five of five readers took a narrow window
// with live content inside for a distortion (a phone mock-up, an hourglass, macOS's genie) and four of five for a
// rendering bug, because its edges cropped the heading and the table's rows, and the mark's bar never reached the
// screen (staging v5/polish/personas/spec-A-answers.json). So the content is never seen through a part of the window:
// it sits above the ground, and an element marked [data-portal-reveal] shows only once the window holds all of it.
// v4c's empty frames (REVIEW-v4 §3.3: a lone window and nothing else on screen) do not come back: the host's heading
// stays on the page above the closed mark.
// Nor is the window ever empty (round 3c, staging v5/round3/c-door/NOTES.md): with only the field inside, five of five
// readers took the closed and half-open mark for an image that did not load (staging REVIEW-v5-round3.md §2.4). An
// element marked [data-portal-hold] (on the v5 page, the card itself) is in the window from the closed mark on: whole,
// scaled to fit the window with HOLD_PAD_PX on every side, carried from the closed window's middle to its own place,
// where it is at full size as the window comes to hold it.
//
// Geometry: the block of the v5 lockup mark, BRAND_MARK.fill (generated by scripts/assets/brand-v5.mjs from
// public/brand/logo-wordmark-onlight.svg), read once and redrawn in px at each size as a CSS clip-path: path() on the
// ground (so the edge is exact at every size), and in the optional 1 px frame with the bar as a line at the mark's
// own gap under it (as public/brand/outline/outline-*.svg draw the mark).
//
// Motion, in three parts of one scroll range (data-portal-range):
// 1. Closed: the window is [data-portal-door]'s box (its width; the block's height follows the mark), or without one
//    data-portal-width px (default 240) centred in the host. The door does not start to open before the whole closed
//    mark, bar included, is on screen with MARK_MARGIN_PX to spare: the range's start is the earliest it may start.
// 2. It grows down and out from its top edge, which stays put: a zoom whose size is geometric in an eased progress
//    (EASE_POW: small steps while the mark is small, so it reads as the mark before it grows). While the window holds
//    every [data-portal-reveal] box with REVEAL_PAD_PX on every side, they are shown (data-portal-shown: a section may
//    hide a reveal until then, so a reader who stops never sees half of it). Until then the hold grows with the window,
//    so a reader who stops sees all of it, smaller. The frame fades out (FADE_G) as the window starts to hold the
//    reveals, or earlier where they only fit at the end (narrow screens): it is gone before part 3.
// 3. Over the zoom's last LIFT_G the top edge rises to the host's top while the window keeps growing (an ease-in, so
//    it leaves no sliver at the top): behind the host's heading, with no line. The window covers the host and the
//    clip is taken away.
//
// Per frame it writes:
//   [data-portal]          data-portal-mode="live", data-portal-state="closed" | "opening" | "open", --portal-p
//                          (0-1 over the range, from the guarded start)
//   [data-portal-window]   style.clipPath = path(...) while not open; nothing once open
//   [data-portal-frame]    style.opacity; [data-portal-outline] d = the block, [data-portal-line] d = the bar's line
//   [data-portal-reveal]   data-portal-shown while the window holds it (and always once open)
//   [data-portal-hold]     style.translate and style.scale (about its centre) until the reveals show; nothing then
// Options on the host: data-portal-range="-0.5,0.5" (where the door opens, in screens of scroll from the moment the
// host's top reaches the viewport's top: negative values start it while the host is still coming in),
// data-portal-width="240" (the closed window without a door element), data-portal-media (default
// "(min-width: 901px) and (min-height: 680px)").
// Not live (no JS, prefers-reduced-motion, outside the media query, or a pin a capture tool set to position: static):
// it writes nothing, and the CSS default shows the content in the flow with no window. Keyboard focus inside the pin
// opens the door at once, so a focused element is never hidden; focus that comes from a pointer press does not (a
// press lands on what is shown).

import { BRAND_MARK } from "../../shared/ui/brand-v5.generated.ts";

const MEDIA = "(min-width: 901px) and (min-height: 680px)";
const RANGE: readonly [number, number] = [-0.5, 0.5];
const CLOSED_PX = 240;
/** The open window clears the host by this much on every side, so its outline and anti-aliased edge are outside. */
const CLEAR_PX = 2;
/** The whole closed mark (its bar's line included) is this far above the viewport's bottom before the door opens. */
const MARK_MARGIN_PX = 24;
/** A [data-portal-reveal] element is shown once the window holds it with this much room on every side. */
const REVEAL_PAD_PX = 24;
/** The [data-portal-hold] element keeps this much room inside the window on every side, at every frame. */
const HOLD_PAD_PX = 24;
/** The zoom's progress (its log scale, 0-1) over which the frame fades out, from where the window starts to hold the
 *  reveals (or earlier, so that it is gone before the lift). */
const FADE_G = 0.06;
/** The zoom's last share, in which the top edge rises behind the host's heading: kept short (20 px of scroll at
 *  1440 x 900, measured). */
const LIFT_G = 0.15;
/**
 * The scroll progress is raised to this power before it drives the zoom: a slow start, a brisk end. At 2 the closed
 * mark has barely grown a fifth of the way in, and halfway through the bar's line is still on screen (1440 x 900).
 */
const EASE_POW = 2;
/** Focus arriving this soon after a pointer press inside the pin counts as the press's. */
const PRESS_FOCUS_MS = 500;

type Seg = { readonly c: "M" | "L" | "C" | "Z"; readonly p: readonly number[] };
type Box = { x: number; y: number; w: number; h: number };

/** Absolute M / L / C / Z segments of path data (H, V and relative forms resolved); [] if it uses anything else. */
function parsePath(d: string): Seg[] {
  const tok = d.match(/[a-zA-Z]|[-+]?(?:\d*\.\d+|\d+\.?)(?:[eE][-+]?\d+)?/g) ?? [];
  const segs: Seg[] = [];
  let i = 0;
  let cmd = "";
  let x = 0;
  let y = 0;
  let sx = 0;
  let sy = 0;
  const n = (): number => Number(tok[i++]);
  while (i < tok.length) {
    if (/^[a-zA-Z]$/.test(tok[i] ?? "")) {
      cmd = tok[i++] ?? "";
    }
    const rel = cmd !== cmd.toUpperCase();
    const ox = rel ? x : 0;
    const oy = rel ? y : 0;
    switch (cmd.toUpperCase()) {
      case "M":
        x = n() + ox;
        y = n() + oy;
        sx = x;
        sy = y;
        segs.push({ c: "M", p: [x, y] });
        cmd = rel ? "l" : "L";
        break;
      case "L":
        x = n() + ox;
        y = n() + oy;
        segs.push({ c: "L", p: [x, y] });
        break;
      case "H":
        x = n() + ox;
        segs.push({ c: "L", p: [x, y] });
        break;
      case "V":
        y = n() + oy;
        segs.push({ c: "L", p: [x, y] });
        break;
      case "C": {
        const p = [n() + ox, n() + oy, n() + ox, n() + oy, n() + ox, n() + oy];
        x = p[4] ?? x;
        y = p[5] ?? y;
        segs.push({ c: "C", p });
        break;
      }
      case "Z":
        x = sx;
        y = sy;
        segs.push({ c: "Z", p: [] });
        cmd = ""; // a number straight after Z is malformed: the default case ends the parse
        break;
      default:
        return [];
    }
  }
  return segs.every((s) => s.p.every(Number.isFinite)) ? segs : [];
}

type Mark = {
  /** The block outline in units of its width, origin at its centre. */
  segs: Seg[];
  /** Block height / width. */
  aspect: number;
  /** How far each concave side bulges in at mid-height, / width (upper bound: from the control points). */
  sag: number;
  /** The bar's top edge below the block's centre, / width: where the 1 px line goes (the mark's gap is kept). */
  floor: number;
};

let markCache: Mark | null | undefined;

/** BRAND_MARK's block, normalised; null if the generated path is not one this engine can redraw. */
function readMark(): Mark | null {
  if (markCache !== undefined) {
    return markCache;
  }
  const segs = parsePath(BRAND_MARK.fill);
  const xs = segs.flatMap((s) => s.p.filter((_, k) => k % 2 === 0));
  const ys = segs.flatMap((s) => s.p.filter((_, k) => k % 2 === 1));
  const x0 = Math.min(...xs);
  const x1 = Math.max(...xs);
  const y0 = Math.min(...ys);
  const y1 = Math.max(...ys);
  const w = x1 - x0;
  if (!segs.length || !(w > 0) || !(y1 > y0)) {
    markCache = null;
    return null;
  }
  const cx = (x0 + x1) / 2;
  const cy = (y0 + y1) / 2;
  const unit = segs.map((s) => ({ c: s.c, p: s.p.map((v, k) => (v - (k % 2 === 0 ? cx : cy)) / w) }));
  const sideXs = unit.filter((s) => s.c === "C").flatMap((s) => s.p.filter((_, k) => k % 2 === 0));
  const sag = Math.max(0, ...sideXs.map((u) => 0.5 - Math.abs(u)));
  const barY = parsePath(BRAND_MARK.bar)[0]?.p[1] ?? y1;
  markCache = { segs: unit, aspect: (y1 - y0) / w, sag, floor: (barY - BRAND_MARK.stroke / 2 - cy) / w };
  return markCache;
}

const clamp01 = (v: number): number => Math.min(1, Math.max(0, v));
const px = (v: number): string => v.toFixed(1);

/** The block as path data, w px wide, centred on (cx, cy). */
function blockPath(mark: Mark, cx: number, cy: number, w: number): string {
  let d = "";
  for (const s of mark.segs) {
    d += s.c;
    for (let k = 0; k + 1 < s.p.length; k += 2) {
      d += `${k ? " " : ""}${px(cx + (s.p[k] ?? 0) * w)} ${px(cy + (s.p[k + 1] ?? 0) * w)}`;
    }
  }
  return d;
}

/**
 * el's border box in the coordinates of root's border box, from layout offsets: a transform, the translate property or
 * an opacity on the way does not move it (the harness switch rolls its values with translate). null when root is not
 * on el's offsetParent chain.
 */
function layoutBox(el: HTMLElement, root: HTMLElement): Box | null {
  let x = root.clientLeft;
  let y = root.clientTop;
  let node: Element | null = el;
  while (node instanceof HTMLElement && node !== root) {
    x += node.offsetLeft;
    y += node.offsetTop;
    node = node.offsetParent;
    if (node instanceof HTMLElement && node !== root) {
      x += node.clientLeft; // offsets run from the parent's padding edge: add its border
      y += node.clientTop;
    }
  }
  return node === root ? { x, y, w: el.offsetWidth, h: el.offsetHeight } : null;
}

function range(raw: string | undefined): readonly [number, number] {
  const [a, b] = (raw ?? "").split(",").map((s) => Number.parseFloat(s));
  return a !== undefined && b !== undefined && Number.isFinite(a) && Number.isFinite(b) && b > a ? [a, b] : RANGE;
}

function mountPortal(host: HTMLElement, mark: Mark): () => void {
  const pin = host.querySelector<HTMLElement>("[data-portal-pin]");
  const layer = host.querySelector<HTMLElement>("[data-portal-window]");
  if (!pin || !layer) {
    return () => {};
  }
  const doorEl = host.querySelector<HTMLElement>("[data-portal-door]");
  const reveals = [...host.querySelectorAll<HTMLElement>("[data-portal-reveal]")];
  const holdEl = host.querySelector<HTMLElement>("[data-portal-hold]");
  const frameEl = host.querySelector<SVGSVGElement>("[data-portal-frame]");
  const outline = frameEl?.querySelector<SVGPathElement>("[data-portal-outline]") ?? null;
  const line = frameEl?.querySelector<SVGPathElement>("[data-portal-line]") ?? null;
  const [a, b] = range(host.dataset["portalRange"]);
  const closedAttr = Number.parseFloat(host.dataset["portalWidth"] ?? "");
  const closedPx = Number.isFinite(closedAttr) && closedAttr > 0 ? closedAttr : CLOSED_PX;
  const media = window.matchMedia(host.dataset["portalMedia"] ?? MEDIA);
  const reduce = window.matchMedia("(prefers-reduced-motion: reduce)");

  let live = false;
  let focusOpen = false; // keyboard focus is inside the pin
  let pressedAt = -Infinity; // the last pointer press inside the pin (performance.now())
  let frame = 0;
  // Measured (px; scroll in px from the host's top at the viewport's top, geometry in the ground's coordinates): the
  // host's document top, the range, the closed and open widths and their ratio, the closed top edge and centre x, the
  // open top edge and the layer's centre x, the reveal boxes, the zoom progress at which the frame starts to fade, and
  // the frame's offset from the ground.
  let top = 0;
  let start = 0;
  let end = 1;
  let w0 = CLOSED_PX;
  let ratio = 1;
  let top0 = 0;
  let cx0 = 0;
  let top1 = -CLEAR_PX;
  let cx1 = 0;
  let boxes: Box[] = [];
  let gFade = 1;
  // The hold: its own layout box, its scale in the closed window, and the zoom progress at which the window holds the
  // reveals (where the hold is at its own place and size).
  let hold: Box | null = null;
  let holdS0 = 1;
  let gShow = 1;
  let shift: { x: number; y: number } = { x: 0, y: 0 };
  let lastP = "";
  let lastState = "";
  let lastClip = "";
  let lastOpacity = "";
  let lastShown: boolean | null = null;
  let lastHold = "";

  const measure = (): void => {
    top = host.getBoundingClientRect().top + window.scrollY;
    const screenPx = document.documentElement.clientHeight || window.innerHeight || 1;
    const W = layer.offsetWidth;
    const H = layer.offsetHeight;
    // A block w wide covers a box (bw, bh) when its narrowest width, at mid-height, spans bw.
    const covering = (bw: number, bh: number): number => Math.max(bw / (1 - 2 * mark.sag), bh / mark.aspect);
    const w1 = covering(W + 2 * CLEAR_PX, H + 2 * CLEAR_PX);
    const origin = layoutBox(layer, pin) ?? { x: 0, y: 0, w: W, h: H };
    const inLayer = (el: HTMLElement): Box | null => {
      const box = layoutBox(el, pin);
      return box ? { x: box.x - origin.x, y: box.y - origin.y, w: box.w, h: box.h } : null;
    };
    const door = doorEl ? inLayer(doorEl) : null;
    if (door && door.w > 0) {
      w0 = Math.min(door.w, w1);
      cx0 = door.x + door.w / 2;
      top0 = door.y;
    } else {
      w0 = Math.min(closedPx, w1);
      cx0 = W / 2;
      top0 = (H - mark.aspect * w0) / 2;
    }
    ratio = w1 / w0;
    cx1 = W / 2;
    top1 = -CLEAR_PX;
    // The reveal boxes, and when the frame fades: as the window starts to hold them all (the least width at which it
    // does with its top edge still at top0, as a share of the zoom), and in any case before the top edge rises.
    boxes = reveals.map((el) => inLayer(el)).filter((box): box is Box => box !== null && box.w > 0);
    let need = 0;
    for (const box of boxes) {
      const half = Math.max(cx0 - (box.x - REVEAL_PAD_PX), box.x + box.w + REVEAL_PAD_PX - cx0);
      need = Math.max(need, (2 * half) / (1 - 2 * mark.sag), (box.y + box.h + REVEAL_PAD_PX - top0) / mark.aspect);
    }
    const gReveal = need <= w0 ? 0 : ratio > 1.0001 ? Math.log(need / w0) / Math.log(ratio) : 1;
    gFade = Math.max(0, Math.min(gReveal, 1 - LIFT_G - FADE_G));
    gShow = Math.min(1, gReveal);
    // The hold, in the closed window: centred, as large as fits with HOLD_PAD_PX on every side (never above 1).
    hold = holdEl ? inLayer(holdEl) : null;
    if (hold && hold.w > 0 && hold.h > 0) {
      const room = (w0 / 2 - mark.sag * w0 - HOLD_PAD_PX) * 2;
      holdS0 = Math.max(0, Math.min(1, room / hold.w, (mark.aspect * w0 - 2 * HOLD_PAD_PX) / hold.h));
    }
    lastHold = "";
    // The range, in px of scroll; its start waits for the whole closed mark, bar included, to be on screen. The pin
    // sits at the host's top, so for a negative scroll the ground's top is that far down the viewport.
    const markBottom = origin.y + top0 + (mark.aspect / 2 + mark.floor) * w0 + 1;
    end = b * screenPx;
    start = Math.min(Math.max(a * screenPx, markBottom + MARK_MARGIN_PX - screenPx), end - 1);
    // The frame is an <svg> (no layout offsets); it and the ground both fill the pin, so this is 0, 0 unless a
    // section moves one of them.
    const lb = layer.getBoundingClientRect();
    const fb = frameEl?.getBoundingClientRect();
    shift = fb ? { x: lb.left - fb.left, y: lb.top - fb.top } : { x: 0, y: 0 };
    lastClip = ""; // sizes changed: redraw even at the same progress
  };

  const setState = (state: string): void => {
    if (state !== lastState) {
      lastState = state;
      host.dataset["portalState"] = state;
    }
  };

  const setShown = (shown: boolean): void => {
    if (shown !== lastShown) {
      lastShown = shown;
      for (const el of reveals) {
        el.toggleAttribute("data-portal-shown", shown);
      }
    }
  };

  const setOpacity = (value: string): void => {
    if (frameEl && value !== lastOpacity) {
      lastOpacity = value;
      frameEl.style.opacity = value;
    }
  };

  /** Moves the hold so its centre is at (x, y) at scale s; null leaves it at its own box. */
  const moveHold = (to: { x: number; y: number; s: number } | null): void => {
    if (!holdEl || !hold) {
      return;
    }
    const dx = to ? to.x - (hold.x + hold.w / 2) : 0;
    const dy = to ? to.y - (hold.y + hold.h / 2) : 0;
    const s = to ? to.s : 1;
    const value =
      Math.abs(dx) < 0.05 && Math.abs(dy) < 0.05 && Math.abs(s - 1) < 1e-4 ? "" : `${px(dx)} ${px(dy)} ${s.toFixed(4)}`;
    if (value === lastHold) {
      return;
    }
    lastHold = value;
    if (value === "") {
      holdEl.style.removeProperty("translate");
      holdEl.style.removeProperty("scale");
    } else {
      holdEl.style.translate = `${px(dx)}px ${px(dy)}px`;
      holdEl.style.scale = s.toFixed(4);
    }
  };

  /**
   * The hold while the reveals are hidden, for a window w wide with its top edge at yTop and its centre at cx: from the
   * closed window's middle at holdS0 to its own place at full size, as the zoom goes from closed to where the window
   * holds the reveals (gShow). Its scale follows that progress; its centre keeps to the middle of the growing window
   * and eases over to its own (a smoothstep). The scale never exceeds what keeps it inside the window with HOLD_PAD_PX
   * on every side (the sides' deepest point counted on every row), so it is whole at every frame.
   */
  const placeHold = (g: number, w: number, yTop: number, cx: number): void => {
    if (!hold || !(hold.w > 0) || !(hold.h > 0)) {
      return;
    }
    const t = gShow > 0 ? clamp01(g / gShow) : 1;
    const k = t * t * (3 - 2 * t);
    const h = mark.aspect * w;
    const x = cx + (hold.x + hold.w / 2 - cx) * k;
    const y = top0 + h / 2 + (hold.y + hold.h / 2 - top0 - h / 2) * k;
    const across = (w / 2 - mark.sag * w - HOLD_PAD_PX - Math.abs(x - cx)) * 2;
    const down = (Math.min(y - yTop, yTop + h - y) - HOLD_PAD_PX) * 2;
    moveHold({ x, y, s: Math.max(0, Math.min(holdS0 + (1 - holdS0) * t, across / hold.w, down / hold.h)) });
  };

  const render = (): void => {
    frame = 0;
    const p = clamp01((window.scrollY - top - start) / (end - start));
    const value = p.toFixed(4);
    if (value !== lastP) {
      lastP = value;
      host.style.setProperty("--portal-p", value);
    }
    if (focusOpen || p >= 1 || ratio <= 1.0001) {
      setState("open");
      setShown(true);
      moveHold(null);
      if (lastClip !== "none") {
        lastClip = "none";
        layer.style.removeProperty("clip-path");
      }
      return;
    }
    setState(p <= 0 ? "closed" : "opening");
    const g = p ** EASE_POW;
    setOpacity((1 - clamp01((g - gFade) / FADE_G)).toFixed(3));
    const w = w0 * ratio ** g;
    const lift = clamp01((g - (1 - LIFT_G)) / LIFT_G);
    const yTop = top0 + (top1 - top0) * lift * lift;
    const cx = cx0 + (cx1 - cx0) * g;
    const cy = yTop + (mark.aspect * w) / 2;
    // Shown while the window holds every reveal box with the pad on every side (the sides' deepest point counted on
    // every row, so the test never passes a box a concave side still crosses).
    const inner = w / 2 - mark.sag * w - REVEAL_PAD_PX;
    const shown = boxes.every(
      (box) =>
        box.y - REVEAL_PAD_PX >= yTop &&
        box.y + box.h + REVEAL_PAD_PX <= yTop + mark.aspect * w &&
        box.x >= cx - inner &&
        box.x + box.w <= cx + inner,
    );
    setShown(shown);
    if (shown) {
      moveHold(null);
    } else {
      placeHold(g, w, yTop, cx);
    }
    const d = blockPath(mark, cx, cy, w);
    if (d === lastClip) {
      return;
    }
    lastClip = d;
    layer.style.clipPath = `path("${d}")`;
    outline?.setAttribute("d", blockPath(mark, cx + shift.x, cy + shift.y, w));
    const ly = px(cy + shift.y + mark.floor * w);
    line?.setAttribute("d", `M${px(cx + shift.x - w / 2)} ${ly}H${px(cx + shift.x + w / 2)}`);
  };

  const schedule = (): void => {
    if (live && !frame) {
      frame = requestAnimationFrame(render);
    }
  };

  const clear = (): void => {
    cancelAnimationFrame(frame);
    frame = 0;
    lastP = "";
    lastState = "";
    lastClip = "";
    lastOpacity = "";
    lastShown = null;
    lastHold = "";
    delete host.dataset["portalMode"];
    delete host.dataset["portalState"];
    host.style.removeProperty("--portal-p");
    layer.style.removeProperty("clip-path");
    frameEl?.style.removeProperty("opacity");
    outline?.removeAttribute("d");
    line?.removeAttribute("d");
    for (const el of reveals) {
      el.removeAttribute("data-portal-shown");
    }
    holdEl?.style.removeProperty("translate");
    holdEl?.style.removeProperty("scale");
  };

  const setMode = (): void => {
    // A capture tool that unsticks the pin (staging tools/capture-v4.ts UNSTICK=1) gets the end state, as in v4c.
    const want = media.matches && !reduce.matches && pin.style.position !== "static";
    if (want !== live) {
      live = want;
      if (!live) {
        clear();
        return;
      }
      host.dataset["portalMode"] = "live"; // the CSS makes the host tall and the pin sticky from here
    }
    if (live) {
      measure();
      render();
    }
  };

  // Focus given by a press was given to something the pointer could reach, so to something shown (a reveal not yet
  // shown takes no pointer events, spec.css): only keyboard and assistive-technology focus needs the door opened.
  const onPointerDown = (): void => {
    pressedAt = performance.now();
  };
  const onFocusIn = (): void => {
    if (!focusOpen && performance.now() - pressedAt > PRESS_FOCUS_MS) {
      focusOpen = true;
      schedule();
    }
  };
  const onFocusOut = (event: FocusEvent): void => {
    if (!(event.relatedTarget instanceof Node && pin.contains(event.relatedTarget))) {
      focusOpen = false;
      schedule();
    }
  };

  // Content above the host (fonts, the pinned stage) moves it; re-measure whenever the page, the host, the door, a
  // reveal or the hold changes size. A web font swapping in moves the door and the card without resizing either
  // (measured on the sandbox: a window framed on the fallback face's box in 3 of 4 loads), so font loads re-measure too.
  const resize = new ResizeObserver(setMode);
  resize.observe(host);
  resize.observe(document.body);
  for (const el of new Set([doorEl, ...reveals, holdEl])) {
    if (el) {
      resize.observe(el);
    }
  }
  document.fonts.addEventListener("loadingdone", setMode);
  const unstick = new MutationObserver(setMode);
  unstick.observe(pin, { attributes: true, attributeFilter: ["style"] });
  media.addEventListener("change", setMode);
  reduce.addEventListener("change", setMode);
  window.addEventListener("resize", setMode, { passive: true });
  window.addEventListener("scroll", schedule, { passive: true });
  pin.addEventListener("pointerdown", onPointerDown, { passive: true });
  pin.addEventListener("focusin", onFocusIn);
  pin.addEventListener("focusout", onFocusOut);
  setMode();

  return () => {
    resize.disconnect();
    unstick.disconnect();
    document.fonts.removeEventListener("loadingdone", setMode);
    media.removeEventListener("change", setMode);
    reduce.removeEventListener("change", setMode);
    window.removeEventListener("resize", setMode);
    window.removeEventListener("scroll", schedule);
    pin.removeEventListener("pointerdown", onPointerDown);
    pin.removeEventListener("focusin", onFocusIn);
    pin.removeEventListener("focusout", onFocusOut);
    live = false;
    clear();
  };
}

/** Wires every [data-portal] in root. Returns a cleanup. */
export function initPortal(root: ParentNode = document): () => void {
  const mark = readMark();
  const hosts = [...root.querySelectorAll<HTMLElement>("[data-portal]")];
  const stops = mark ? hosts.map((host) => mountPortal(host, mark)) : [];
  return () => {
    for (const stop of stops) {
      stop();
    }
  };
}
