// Portal (v5 graft of v4c's scroll motion; owner 10-20: 「滚动的动效我觉得是有说法的」), declared with [data-portal].
// A sticky host whose content is seen through the mosoo mark's block, the concave-sided window of the logo outline:
// the window starts small, then grows with the scroll until it covers the host and is taken away.
//
// Reverse-engineered from:
// - Enter Pro's door mask (staging refs/enter-pro/notes.md §3 row 4; cdp2/cssom-rules.json): `.anything-scene` is a
//   full-size layer over a 455vh + 100vh sticky stage, masked with portal.svg, and the mask's size and position are
//   scrubbed until the door covers the screen. The scene behind the door is real content from the first frame.
// - v4c (redesign/v4c apps/landing/src/effects/stage.ts): the same block path redrawn at every size (not scaled), so
//   the 1 px outline stays one pixel, and the clip taken away once the block covers the stage. v4c's empty frames
//   (staging v4c/proof/stage-fix/sheet.jpg: p = .05-.06 a lone window holding only a veil of bands, p = .37 nothing
//   but the nav; REVIEW-v4 §3.3) came from hiding the content until the window was wide. Here the window always
//   shows the content behind it, and nothing in the host is ever hidden: no veil, no opacity, no leave-then-enter.
//
// Geometry: the block of the v5 lockup mark, BRAND_MARK.fill (generated by scripts/assets/brand-v5.mjs from
// public/brand/logo-wordmark-onlight.svg), read once and redrawn in px at each size as a CSS clip-path: path(), so
// the edge is exact at every size and the clipped-away content is not hit-testable (a mask-image would still take
// clicks). The optional 1 px frame redraws the same path, plus the mark's bar as a line under it.
//
// Motion: one zoom about a fixed point. The closed window stands on the host's vertical axis (the page's, as the mark
// it is: v5 fix round, staging v5/review/graft-design.md P2-1, where a window centred on an off-axis focus sat 55 px
// off the page's axis and cut the line under it). Without [data-portal-focus] it is centred in the host; with one it
// is level with the focus, and wide enough to show the focus whole with FOCUS_PAD_PX to spare on both sides of the
// axis; data-portal-room="px" hangs it from the focus instead: its top edge that far above the focus's top (the
// room for what sits above the focus, so the window's top falls in a gap and cuts no line). It is at least
// data-portal-width wide (default 240 px). The open window is centred and just covers the host. Every frame in
// between is the closed window scaled about the one point that maps it onto the open one, so what the reader sees
// through the closed window stays put while the door opens around it. The scale is geometric in the progress (equal
// scroll, equal zoom ratio): small steps while the window is small, and the sides leave the screen briskly at the
// end instead of creeping along its edges (a smoothstep left 1-35 px slivers over the last tenth of the range).
//
// Per frame it writes:
//   [data-portal]          data-portal-mode="live", data-portal-state="closed" | "opening" | "open", --portal-p
//                          (0-1 over the range)
//   [data-portal-window]   style.clipPath = path(...) while not open; nothing once open
//   [data-portal-outline]  d = the block, [data-portal-line] d = the bar's line (both optional, in [data-portal-frame])
// Options on the host: data-portal-range="-0.5,0.5" (where the door opens, in screens of scroll from the moment the
// host's top reaches the viewport's top: negative values start it while the host is still coming in),
// data-portal-width="240" (the closed window's least width), data-portal-room (px above the focus, see Motion),
// data-portal-media (default "(min-width: 901px) and (min-height: 680px)").
// Not live (no JS, prefers-reduced-motion, outside the media query, or a pin a capture tool set to position: static):
// it writes nothing, and the CSS default shows the content in the flow with no window. Focus inside the window opens
// it at once, so a focused element is never clipped away, unless the focus came from a pointer press: a press can
// only land on the visible part.

import { BRAND_MARK } from "../../shared/ui/brand-v5.generated.ts";

const MEDIA = "(min-width: 901px) and (min-height: 680px)";
const RANGE: readonly [number, number] = [-0.5, 0.5];
const CLOSED_PX = 240;
/** The closed window frames [data-portal-focus] with at least this much room on every side. */
const FOCUS_PAD_PX = 16;
/** The open window clears the host by this much on every side, so its outline and anti-aliased edge are outside. */
const CLEAR_PX = 2;
/** Focus arriving this soon after a pointer press inside the window counts as the press's. */
const PRESS_FOCUS_MS = 500;

type Seg = { readonly c: "M" | "L" | "C" | "Z"; readonly p: readonly number[] };
type Point = { x: number; y: number };

/** Absolute M / L / C / Z segments of path data (H, V and relative forms resolved); [] if it uses anything else. */
function parsePath(d: string): Seg[] {
  const tok = d.match(/[a-zA-Z]|[-+]?(?:\d*\.\d+|\d+\.?)(?:[eE][-+]?\d+)?/g) ?? [];
  const segs: Seg[] = [];
  let i = 0;
  let cmd = "";
  let x = 0;
  let y = 0;
  let sx = 0;
  let sy = 0;
  const n = (): number => Number(tok[i++]);
  while (i < tok.length) {
    if (/^[a-zA-Z]$/.test(tok[i] ?? "")) {
      cmd = tok[i++] ?? "";
    }
    const rel = cmd !== cmd.toUpperCase();
    const ox = rel ? x : 0;
    const oy = rel ? y : 0;
    switch (cmd.toUpperCase()) {
      case "M":
        x = n() + ox;
        y = n() + oy;
        sx = x;
        sy = y;
        segs.push({ c: "M", p: [x, y] });
        cmd = rel ? "l" : "L";
        break;
      case "L":
        x = n() + ox;
        y = n() + oy;
        segs.push({ c: "L", p: [x, y] });
        break;
      case "H":
        x = n() + ox;
        segs.push({ c: "L", p: [x, y] });
        break;
      case "V":
        y = n() + oy;
        segs.push({ c: "L", p: [x, y] });
        break;
      case "C": {
        const p = [n() + ox, n() + oy, n() + ox, n() + oy, n() + ox, n() + oy];
        x = p[4] ?? x;
        y = p[5] ?? y;
        segs.push({ c: "C", p });
        break;
      }
      case "Z":
        x = sx;
        y = sy;
        segs.push({ c: "Z", p: [] });
        cmd = ""; // a number straight after Z is malformed: the default case ends the parse
        break;
      default:
        return [];
    }
  }
  return segs.every((s) => s.p.every(Number.isFinite)) ? segs : [];
}

type Mark = {
  /** The block outline in units of its width, origin at its centre. */
  segs: Seg[];
  /** Block height / width. */
  aspect: number;
  /** How far each concave side bulges in at mid-height, / width (upper bound: from the control points). */
  sag: number;
  /** The bar's top edge below the block's centre, / width: where the 1 px line goes (the mark's gap is kept). */
  floor: number;
};

let markCache: Mark | null | undefined;

/** BRAND_MARK's block, normalised; null if the generated path is not one this engine can redraw. */
function readMark(): Mark | null {
  if (markCache !== undefined) {
    return markCache;
  }
  const segs = parsePath(BRAND_MARK.fill);
  const xs = segs.flatMap((s) => s.p.filter((_, k) => k % 2 === 0));
  const ys = segs.flatMap((s) => s.p.filter((_, k) => k % 2 === 1));
  const x0 = Math.min(...xs);
  const x1 = Math.max(...xs);
  const y0 = Math.min(...ys);
  const y1 = Math.max(...ys);
  const w = x1 - x0;
  if (!segs.length || !(w > 0) || !(y1 > y0)) {
    markCache = null;
    return null;
  }
  const cx = (x0 + x1) / 2;
  const cy = (y0 + y1) / 2;
  const unit = segs.map((s) => ({ c: s.c, p: s.p.map((v, k) => (v - (k % 2 === 0 ? cx : cy)) / w) }));
  const sideXs = unit.filter((s) => s.c === "C").flatMap((s) => s.p.filter((_, k) => k % 2 === 0));
  const sag = Math.max(0, ...sideXs.map((u) => 0.5 - Math.abs(u)));
  const barY = parsePath(BRAND_MARK.bar)[0]?.p[1] ?? y1;
  markCache = { segs: unit, aspect: (y1 - y0) / w, sag, floor: (barY - BRAND_MARK.stroke / 2 - cy) / w };
  return markCache;
}

const clamp01 = (v: number): number => Math.min(1, Math.max(0, v));
const px = (v: number): string => v.toFixed(1);

/** The block as path data, w px wide, centred on (cx, cy). */
function blockPath(mark: Mark, cx: number, cy: number, w: number): string {
  let d = "";
  for (const s of mark.segs) {
    d += s.c;
    for (let k = 0; k + 1 < s.p.length; k += 2) {
      d += `${k ? " " : ""}${px(cx + (s.p[k] ?? 0) * w)} ${px(cy + (s.p[k + 1] ?? 0) * w)}`;
    }
  }
  return d;
}

/**
 * el's border box in the coordinates of layer's border box, from layout offsets: a transform or the translate property
 * on the way does not move it. The focus can be a value the harness switch has rolled away (translate 0 -55%); a
 * re-measure then (a FAQ item opening resizes the body) framed the closed window 24 px off its value, measured.
 * null when layer is not on el's offsetParent chain.
 */
function layoutBox(el: HTMLElement, layer: HTMLElement): { x: number; y: number; w: number; h: number } | null {
  let x = layer.clientLeft;
  let y = layer.clientTop;
  let node: Element | null = el;
  while (node instanceof HTMLElement && node !== layer) {
    x += node.offsetLeft;
    y += node.offsetTop;
    node = node.offsetParent;
    if (node instanceof HTMLElement && node !== layer) {
      x += node.clientLeft; // offsets run from the parent's padding edge: add its border
      y += node.clientTop;
    }
  }
  return node === layer ? { x, y, w: el.offsetWidth, h: el.offsetHeight } : null;
}

function range(raw: string | undefined): readonly [number, number] {
  const [a, b] = (raw ?? "").split(",").map((s) => Number.parseFloat(s));
  return a !== undefined && b !== undefined && Number.isFinite(a) && Number.isFinite(b) && b > a ? [a, b] : RANGE;
}

function mountPortal(host: HTMLElement, mark: Mark): () => void {
  const pin = host.querySelector<HTMLElement>("[data-portal-pin]");
  const layer = host.querySelector<HTMLElement>("[data-portal-window]");
  if (!pin || !layer) {
    return () => {};
  }
  const focusEl = layer.querySelector<HTMLElement>("[data-portal-focus]");
  const frameEl = host.querySelector<SVGSVGElement>("[data-portal-frame]");
  const outline = frameEl?.querySelector<SVGPathElement>("[data-portal-outline]") ?? null;
  const line = frameEl?.querySelector<SVGPathElement>("[data-portal-line]") ?? null;
  const [a, b] = range(host.dataset["portalRange"]);
  const closedAttr = Number.parseFloat(host.dataset["portalWidth"] ?? "");
  const closedPx = Number.isFinite(closedAttr) && closedAttr > 0 ? closedAttr : CLOSED_PX;
  const roomAttr = Number.parseFloat(host.dataset["portalRoom"] ?? "");
  const room = Number.isFinite(roomAttr) && roomAttr >= 0 ? roomAttr : null; // null: level with the focus
  const media = window.matchMedia(host.dataset["portalMedia"] ?? MEDIA);
  const reduce = window.matchMedia("(prefers-reduced-motion: reduce)");

  let live = false;
  let revealed = false; // keyboard focus is inside the window
  let pressedAt = -Infinity; // the last pointer press inside the window (performance.now())
  let frame = 0;
  // Measured: the host's document top, one screen, the closed and open widths, their ratio, the closed and open
  // centres, the fixed point of the zoom, and the frame's offset from the window layer (all px, layer coordinates).
  let top = 0;
  let screenPx = 1;
  let w0 = CLOSED_PX;
  let ratio = 1;
  let c0: Point = { x: 0, y: 0 };
  let fixed: Point = { x: 0, y: 0 };
  let shift: Point = { x: 0, y: 0 };
  let lastP = "";
  let lastState = "";
  let lastClip = "";

  const measure = (): void => {
    top = host.getBoundingClientRect().top + window.scrollY;
    screenPx = document.documentElement.clientHeight || window.innerHeight || 1;
    const W = layer.offsetWidth;
    const H = layer.offsetHeight;
    // A block w wide covers a box (bw, bh) centred on it when its narrowest width, at mid-height, spans bw.
    const covering = (bw: number, bh: number): number => Math.max(bw / (1 - 2 * mark.sag), bh / mark.aspect);
    const w1 = covering(W + 2 * CLEAR_PX, H + 2 * CLEAR_PX);
    const box = layer.getBoundingClientRect();
    const c1 = { x: W / 2, y: H / 2 };
    if (focusEl) {
      const r = focusEl.getBoundingClientRect();
      const f = layoutBox(focusEl, layer) ?? { x: r.left - box.left, y: r.top - box.top, w: r.width, h: r.height };
      // On the axis: as wide as the focus's farther side from it, twice, plus the pad on both sides.
      const span = 2 * (Math.max(c1.x - f.x, f.x + f.w - c1.x) + FOCUS_PAD_PX);
      const tall = room === null ? f.h + 2 * FOCUS_PAD_PX : room + f.h + FOCUS_PAD_PX;
      w0 = Math.min(Math.max(closedPx, covering(span, tall)), w1);
      const y = room === null ? f.y + f.h / 2 : f.y - room + (mark.aspect * w0) / 2;
      c0 = { x: c1.x, y };
    } else {
      c0 = c1;
      w0 = Math.min(closedPx, w1);
    }
    ratio = w1 / w0;
    // Scaling the closed window by `ratio` about `fixed` lands it on the open one: c1 = fixed + ratio (c0 - fixed).
    fixed = ratio > 1.0001 ? { x: (c1.x - ratio * c0.x) / (1 - ratio), y: (c1.y - ratio * c0.y) / (1 - ratio) } : c1;
    const fb = frameEl?.getBoundingClientRect();
    shift = fb ? { x: box.left - fb.left, y: box.top - fb.top } : { x: 0, y: 0 };
    lastClip = ""; // sizes changed: redraw even at the same progress
  };

  const setState = (state: string): void => {
    if (state !== lastState) {
      lastState = state;
      host.dataset["portalState"] = state;
    }
  };

  const render = (): void => {
    frame = 0;
    const p = clamp01(((window.scrollY - top) / screenPx - a) / (b - a));
    const value = p.toFixed(4);
    if (value !== lastP) {
      lastP = value;
      host.style.setProperty("--portal-p", value);
    }
    if (revealed || p >= 1 || ratio <= 1.0001) {
      setState("open");
      if (lastClip !== "none") {
        lastClip = "none";
        layer.style.removeProperty("clip-path");
      }
      return;
    }
    setState(p <= 0 ? "closed" : "opening");
    const s = ratio ** p;
    const w = w0 * s;
    const cx = fixed.x + s * (c0.x - fixed.x);
    const cy = fixed.y + s * (c0.y - fixed.y);
    const d = blockPath(mark, cx, cy, w);
    if (d === lastClip) {
      return;
    }
    lastClip = d;
    layer.style.clipPath = `path("${d}")`;
    outline?.setAttribute("d", blockPath(mark, cx + shift.x, cy + shift.y, w));
    const ly = px(cy + shift.y + mark.floor * w);
    line?.setAttribute("d", `M${px(cx + shift.x - w / 2)} ${ly}H${px(cx + shift.x + w / 2)}`);
  };

  const schedule = (): void => {
    if (live && !frame) {
      frame = requestAnimationFrame(render);
    }
  };

  const clear = (): void => {
    cancelAnimationFrame(frame);
    frame = 0;
    lastP = "";
    lastState = "";
    lastClip = "";
    delete host.dataset["portalMode"];
    delete host.dataset["portalState"];
    host.style.removeProperty("--portal-p");
    layer.style.removeProperty("clip-path");
    outline?.removeAttribute("d");
    line?.removeAttribute("d");
  };

  const setMode = (): void => {
    // A capture tool that unsticks the pin (staging tools/capture-v4.ts UNSTICK=1) gets the end state, as in v4c.
    const want = media.matches && !reduce.matches && pin.style.position !== "static";
    if (want !== live) {
      live = want;
      if (!live) {
        clear();
        return;
      }
      host.dataset["portalMode"] = "live"; // the CSS makes the host tall and the pin sticky from here
    }
    if (live) {
      measure();
      render();
    }
  };

  // Focus given by a press was given to something the pointer could reach, so inside the visible window (clip-path
  // clips hit-testing too): only keyboard and assistive-technology focus needs the window opened.
  const onPointerDown = (): void => {
    pressedAt = performance.now();
  };
  const onFocusIn = (): void => {
    if (!revealed && performance.now() - pressedAt > PRESS_FOCUS_MS) {
      revealed = true;
      schedule();
    }
  };
  const onFocusOut = (event: FocusEvent): void => {
    if (!(event.relatedTarget instanceof Node && layer.contains(event.relatedTarget))) {
      revealed = false;
      schedule();
    }
  };

  // Content above the host (fonts, the pinned stage) moves it; re-measure whenever the page or the host changes size.
  // A web font swapping in moves and resizes the focus without resizing either (measured on the sandbox: the closed
  // window was framed on the fallback face's box in 3 of 4 loads), so the focus and font loads re-measure too.
  const resize = new ResizeObserver(setMode);
  resize.observe(host);
  resize.observe(document.body);
  if (focusEl) {
    resize.observe(focusEl);
  }
  document.fonts.addEventListener("loadingdone", setMode);
  const unstick = new MutationObserver(setMode);
  unstick.observe(pin, { attributes: true, attributeFilter: ["style"] });
  media.addEventListener("change", setMode);
  reduce.addEventListener("change", setMode);
  window.addEventListener("resize", setMode, { passive: true });
  window.addEventListener("scroll", schedule, { passive: true });
  layer.addEventListener("pointerdown", onPointerDown, { passive: true });
  layer.addEventListener("focusin", onFocusIn);
  layer.addEventListener("focusout", onFocusOut);
  setMode();

  return () => {
    resize.disconnect();
    unstick.disconnect();
    document.fonts.removeEventListener("loadingdone", setMode);
    media.removeEventListener("change", setMode);
    reduce.removeEventListener("change", setMode);
    window.removeEventListener("resize", setMode);
    window.removeEventListener("scroll", schedule);
    layer.removeEventListener("pointerdown", onPointerDown);
    layer.removeEventListener("focusin", onFocusIn);
    layer.removeEventListener("focusout", onFocusOut);
    live = false;
    clear();
  };
}

/** Wires every [data-portal] in root. Returns a cleanup. */
export function initPortal(root: ParentNode = document): () => void {
  const mark = readMark();
  const hosts = [...root.querySelectorAll<HTMLElement>("[data-portal]")];
  const stops = mark ? hosts.map((host) => mountPortal(host, mark)) : [];
  return () => {
    for (const stop of stops) {
      stop();
    }
  };
}
