#!/usr/bin/env node
// Inline, ink-only runtime glyphs for the four harnesses the home names.
//
//   node apps/landing/scripts/assets/runtime-glyphs.mjs [<piSvg>]
//
// UI-FORMS c.0: runtime glyphs are desaturated to ink on the site (colour belongs to the plates only), so
// the page uses the monochrome files of @lobehub/icons-static-svg (MIT, already a landing dependency;
// the same files the mosoo console uses, MAIN apps/web/src/shared/ui/brand-icons/runtime-icon-data.ts)
// and draws them inline with currentColor: no request, no colour.
//   openai-runtime   -> openai.svg      (MAIN pkgs/runtime-catalog/src/catalog.ts iconKey "openai")
//   claude-agent-sdk -> claudecode.svg  (iconKey "claude-code")
//   acp-fallback     -> opencode.svg    (iconKey "opencode")
//   pi               -> pi.svg          (lobehub 1.94.0, which MAIN locks; this site ships 1.91.0 without it,
//                                        so the file is read from the staging copy, default path below)
// Also three UI glyphs, inner markup kept as drawn (stroke icons, 24 grid, 1.5 stroke):
//   environments -> MAIN docs/design/assets/sidebar-icons/environments.svg (mosoo's own sidebar family)
//   key, copy    -> Hugeicons Free 4.2.3 (MIT) Key02 / Copy01 as the console registers them
//                   (MAIN apps/web/src/shared/ui/icons.tsx), read from the staging byte copies.
// Writes apps/landing/src/home/runtime-glyphs.ts.

import { readFileSync, writeFileSync } from "node:fs";
import { dirname, join, resolve } from "node:path";
import { fileURLToPath } from "node:url";

const HERE = dirname(fileURLToPath(import.meta.url));
const ICONS = resolve(HERE, "../../../../node_modules/@lobehub/icons-static-svg/icons");
const PI = resolve(process.argv[2] ?? "/Users/chenxiefan/Documents/mosoo-website-redesign-staging/refs/devices/elements/svg/runtime-pi.src.svg");
const OUT = resolve(HERE, "../../src/home/runtime-glyphs.ts");

const SOURCES = [
  { id: "openai-runtime", name: "OpenAI Codex", file: join(ICONS, "openai.svg") },
  { id: "claude-agent-sdk", name: "Claude Agent SDK", file: join(ICONS, "claudecode.svg") },
  { id: "acp-fallback", name: "OpenCode", file: join(ICONS, "opencode.svg") },
  { id: "pi", name: "Pi", file: PI },
];

const STAGING_SVG = "/Users/chenxiefan/Documents/mosoo-website-redesign-staging/refs/devices/elements/svg";
const MAIN = "/Users/chenxiefan/.superset/worktrees/mosoo/excellent-frost-5baed21b";
const UI_SOURCES = [
  { id: "environments", file: join(MAIN, "docs/design/assets/sidebar-icons/environments.svg") },
  { id: "key", file: join(STAGING_SVG, "glyph-KeyRound.src.svg") },
  { id: "copy", file: join(STAGING_SVG, "glyph-Copy.src.svg") },
];
const uiGlyphs = UI_SOURCES.map(({ id, file }) => {
  const svg = readFileSync(file, "utf8");
  const open = svg.match(/<svg\b([^>]*)>/);
  const viewBox = open?.[1].match(/viewBox="([^"]+)"/)?.[1];
  const stroke = /stroke="currentColor"/.test(open?.[1] ?? "");
  const inner = svg.slice((open?.index ?? 0) + (open?.[0].length ?? 0), svg.lastIndexOf("</svg>")).replace(/\s*\n\s*/g, "").replace(/<title>.*?<\/title>/g, "");
  if (!viewBox || !inner) throw new Error(`unreadable ${file}`);
  return { id, viewBox, body: inner, stroke };
});

const glyphs = SOURCES.map(({ id, name, file }) => {
  const svg = readFileSync(file, "utf8");
  const viewBox = svg.match(/viewBox="([^"]+)"/)?.[1];
  // Keep only the drawing: <path>, with its d and the even-odd rules; drop titles, fills and styles.
  const paths = [...svg.matchAll(/<path\b([^>]*?)\/?>(?:<\/path>)?/g)].map((m) => {
    const attrs = m[1];
    const d = attrs.match(/\sd="([^"]+)"/)?.[1];
    const clip = /clip-rule="evenodd"/.test(attrs) ? ' clip-rule="evenodd"' : "";
    if (!d) throw new Error(`no d in ${file}`);
    return `<path d="${d}"${clip}/>`;
  });
  if (!viewBox || paths.length === 0) throw new Error(`unreadable ${file}`);
  return { id, name, viewBox, body: paths.join("") };
});

const ts = `// Generated by apps/landing/scripts/assets/runtime-glyphs.mjs. Do not edit.
// Monochrome runtime glyphs (@lobehub/icons-static-svg, MIT), drawn in currentColor.

export type RuntimeGlyph = { id: string; name: string; viewBox: string; body: string };

export const RUNTIME_GLYPHS: readonly RuntimeGlyph[] = ${JSON.stringify(glyphs, null, 2)};

export type UiGlyph = { id: string; viewBox: string; body: string; stroke: boolean };

export const UI_GLYPHS: readonly UiGlyph[] = ${JSON.stringify(uiGlyphs, null, 2)};
`;
writeFileSync(OUT, ts);
console.log(JSON.stringify([...glyphs, ...uiGlyphs].map((g) => ({ id: g.id, viewBox: g.viewBox, bytes: g.body.length }))));
