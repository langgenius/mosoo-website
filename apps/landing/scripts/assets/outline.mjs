#!/usr/bin/env node
// The mosoo logo-outline system for the v4c home: one form, drawn as a window (1px) standing on a line.
//
//   node apps/landing/scripts/assets/outline.mjs
//
// Ported from mosoo-website-redesign-staging/brand/outline/src/gen.mjs (geometry unchanged) and trimmed
// to what the c-stage variant uses (UI-FORMS §d: hero window + portal transition, session line, FAQ
// indicator). Writes:
//   apps/landing/public/brand/outline/{outline-112,portal-mask,session-line,faq-indicator-closed,faq-indicator-open}.svg
//   apps/landing/src/home/outline-geometry.ts   (path data for the inline SVGs and the portal clip-path)
//
// Mark source: apps/landing/public/brand/logo-mark.svg
//   block  M68.15,16.64 H16.64 c.93,5.95 1.47,12.97 1.47,20.48 ... (51.51 x 40.96, sides concave by 1.47)
//   bar    rect 16.64,61.23 51.51 x 6.93 (3.63 under the block; block + gap + bar = 51.52, a square)
// The bar becomes a line at the bar's top edge, so the mark's gap is kept; nothing is stacked vertically
// and nothing is green (brand/outline/README.md §5.2), so the form never reads as a bamboo node.

import { mkdirSync, writeFileSync } from "node:fs";
import { dirname, join, resolve } from "node:path";
import { fileURLToPath } from "node:url";

const HERE = dirname(fileURLToPath(import.meta.url));
const PUBLIC_OUT = resolve(HERE, "../../public/brand/outline");
const TS_OUT = resolve(HERE, "../../src/home/outline-geometry.ts");
mkdirSync(PUBLIC_OUT, { recursive: true });

const M = { w: 51.51, h: 40.96, sag: 1.47, gap: 3.63 };
const BAR_Y = M.h + M.gap; // 44.59
// Control-point ratios read off the original cubic (c.93,5.95 1.47,12.97 1.47,20.48 over half-height 20.48).
const K1 = 0.93 / 1.47;
const K2 = 5.95 / 20.48;
const K3 = 12.97 / 20.48;
const r = (n) => +n.toFixed(3);

function block(x, y, w, h, s) {
  const hh = h / 2;
  return [
    `M${r(x)} ${r(y)}H${r(x + w)}`,
    `C${r(x + w - K1 * s)} ${r(y + K2 * hh)} ${r(x + w - s)} ${r(y + K3 * hh)} ${r(x + w - s)} ${r(y + hh)}`,
    `C${r(x + w - s)} ${r(y + h - K3 * hh)} ${r(x + w - K1 * s)} ${r(y + h - K2 * hh)} ${r(x + w)} ${r(y + h)}`,
    `H${r(x)}`,
    `C${r(x + K1 * s)} ${r(y + h - K2 * hh)} ${r(x + s)} ${r(y + h - K3 * hh)} ${r(x + s)} ${r(y + hh)}`,
    `C${r(x + s)} ${r(y + K3 * hh)} ${r(x + K1 * s)} ${r(y + K2 * hh)} ${r(x)} ${r(y)}Z`,
  ].join("");
}

const svg = (vb, w, h, body, extra = "") =>
  `<svg xmlns="http://www.w3.org/2000/svg" viewBox="${vb}" width="${r(w)}" height="${r(h)}" fill="none"${extra}>\n${body}\n</svg>\n`;

// Hero window: block 112 px wide, 1 px line (README §5.1 "hero 门": 104-132 px, 1 px ink #1a1a1c).
const PAD = 1.2;
const VB_W = M.w + 2 * PAD;
const VB_H = BAR_Y + 2 * PAD;
const HERO_BLOCK = block(PAD, PAD, M.w, M.h, M.sag);
const HERO_LINE = `M${r(PAD)} ${r(PAD + BAR_Y)}H${r(PAD + M.w)}`;
{
  const size = 112;
  const k = size / M.w;
  const sw = r(1 / k);
  writeFileSync(
    join(PUBLIC_OUT, "outline-112.svg"),
    svg(`0 0 ${r(VB_W)} ${r(VB_H)}`, VB_W * k, VB_H * k, `  <path d="${HERO_BLOCK}" stroke="currentColor" stroke-width="${sw}"/>\n  <path d="${HERO_LINE}" stroke="currentColor" stroke-width="${sw}"/>`, ` color="#1a1a1c"`),
  );
}

// Portal mask: the block, filled, tight viewBox.
writeFileSync(
  join(PUBLIC_OUT, "portal-mask.svg"),
  svg(`0 0 ${M.w} ${M.h}`, M.w * 4, M.h * 4, `  <path d="${block(0, 0, M.w, M.h, M.sag)}" fill="#000"/>`, ` preserveAspectRatio="none"`),
);

// Session line: the bar becomes a 1 px line; a 28 px window stands on it once.
const SESSION = (() => {
  const W = 960;
  const bw = 28;
  const k = bw / M.w;
  const bh = M.h * k;
  const y = 0.5 + bh + M.gap * k;
  const x0 = 640;
  return { W, y: r(y), h: r(y + 1), x0, bw, window: block(x0, 0.5, bw, bh, M.sag * k) };
})();
writeFileSync(
  join(PUBLIC_OUT, "session-line.svg"),
  svg(`0 0 ${SESSION.W} ${SESSION.h}`, SESSION.W, SESSION.h, `  <path d="M0 ${SESSION.y}H${SESSION.W}" stroke="currentColor" stroke-width="1"/>\n  <path d="${SESSION.window}" stroke="currentColor" stroke-width="1"/>`, ` color="#1a1a1c"`),
);

// FAQ indicator: 10 px block, 1 px stroke; open = filled.
const FAQ = (() => {
  const bw = 10;
  const k = bw / M.w;
  const bh = M.h * k;
  return { w: 11, h: r(bh + 1), d: block(0.5, 0.5, bw, bh, M.sag * k) };
})();
for (const open of [false, true]) {
  writeFileSync(
    join(PUBLIC_OUT, `faq-indicator-${open ? "open" : "closed"}.svg`),
    svg(`0 0 ${FAQ.w} ${FAQ.h}`, FAQ.w, FAQ.h, `  <path d="${FAQ.d}" stroke="currentColor" stroke-width="1"${open ? ' fill="currentColor"' : ""}/>`, ` color="#1a1a1c"`),
  );
}

// Nav mark: the original solid block + bar, monochrome (README §5.3: 24 px, solid, static).
const NAV = { vb: `0 0 ${M.w} ${r(M.h + M.gap + 6.93)}`, block: block(0, 0, M.w, M.h, M.sag), bar: { y: r(M.h + M.gap), h: 6.93 } };

const ts = `// Generated by apps/landing/scripts/assets/outline.mjs. Do not edit.
// Geometry of the mosoo logo outline (block 51.51 x 40.96, sides concave by 1.47; the bar is a line).

export const OUTLINE = ${JSON.stringify({ w: M.w, h: M.h, sag: M.sag, gap: M.gap, k1: r(K1), k2: r(K2), k3: r(K3) })} as const;

/** Hero window, viewBox ${r(VB_W)} x ${r(VB_H)}: the block and the line it stands on. */
export const HERO_WINDOW = ${JSON.stringify({ viewBox: `0 0 ${r(VB_W)} ${r(VB_H)}`, w: r(VB_W), h: r(VB_H), pad: PAD, block: HERO_BLOCK, line: HERO_LINE })} as const;

/** Session line with one 28 px window standing on it (viewBox ${SESSION.W} x ${SESSION.h}). */
export const SESSION_LINE = ${JSON.stringify(SESSION)} as const;

/** FAQ indicator, 11 x ${FAQ.h}. */
export const FAQ_INDICATOR = ${JSON.stringify(FAQ)} as const;

/** Solid nav mark (monochrome). */
export const NAV_MARK = ${JSON.stringify(NAV)} as const;
`;
writeFileSync(TS_OUT, ts);
console.log(JSON.stringify({ out: [PUBLIC_OUT, TS_OUT], heroViewBox: `0 0 ${r(VB_W)} ${r(VB_H)}` }));
