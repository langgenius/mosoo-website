// mosoo logo-outline geometry: the block drawn as a window (1px line), the bar
// drawn as a line the window stands on. Ported from the staging study
// (brand/outline/src/gen.mjs, 2026-10-19); the numbers are the same.
//
// Mark source: apps/landing/public/brand/logo-mark.svg
//   block  M68.15,16.64 H16.64 c.93,5.95 1.47,12.97 1.47,20.48 s-.54,14.52 -1.47,20.48 h51.51 ...
//          (51.51 x 40.96, sides concave by 1.47)
//   bar    rect 16.64,61.23 51.51 x 6.93 (gap 3.63 under the block)
//
// Run: node apps/landing/scripts/assets/outline.mjs
// Writes public/brand/outline/*.svg and src/shared/brand/outline-paths.ts.
// Deterministic: same input, same bytes.
import { mkdirSync, writeFileSync } from "node:fs";
import { dirname, join } from "node:path";
import { fileURLToPath } from "node:url";

const landing = join(dirname(fileURLToPath(import.meta.url)), "..", "..");
const svgOut = join(landing, "public", "brand", "outline");
const tsOut = join(landing, "src", "shared", "brand", "outline-paths.ts");
mkdirSync(svgOut, { recursive: true });
mkdirSync(dirname(tsOut), { recursive: true });

const M = { w: 51.51, h: 40.96, sag: 1.47, gap: 3.63, barH: 6.93 };
// The line sits where the bar's top edge was, so the mark's gap is kept.
M.barMid = M.h + M.gap;
// Control-point ratios read off the original cubic (c.93,5.95 1.47,12.97 1.47,20.48 over half-height 20.48).
const K1 = 0.93 / 1.47;
const K2 = 5.95 / 20.48;
const K3 = 12.97 / 20.48;
const r = (n) => +n.toFixed(3);

function block(x, y, w, h, s) {
  const hh = h / 2;
  return [
    `M${r(x)} ${r(y)}H${r(x + w)}`,
    `C${r(x + w - K1 * s)} ${r(y + K2 * hh)} ${r(x + w - s)} ${r(y + K3 * hh)} ${r(x + w - s)} ${r(y + hh)}`,
    `C${r(x + w - s)} ${r(y + h - K3 * hh)} ${r(x + w - K1 * s)} ${r(y + h - K2 * hh)} ${r(x + w)} ${r(y + h)}`,
    `H${r(x)}`,
    `C${r(x + K1 * s)} ${r(y + h - K2 * hh)} ${r(x + s)} ${r(y + h - K3 * hh)} ${r(x + s)} ${r(y + hh)}`,
    `C${r(x + s)} ${r(y + K3 * hh)} ${r(x + K1 * s)} ${r(y + K2 * hh)} ${r(x)} ${r(y)}Z`,
  ].join("");
}

// Nested: level k grows by band b on top and both sides; bottoms are shared
// (Enter Pro's arches share the floor). The sag scales with width so every
// level is the same form.
function nested(levels = 3, bandRatio = 0.22) {
  const b = M.w * bandRatio;
  const outerW = M.w + 2 * b * (levels - 1);
  const outerH = M.h + b * (levels - 1);
  const shapes = [];
  for (let k = levels - 1; k >= 0; k--) {
    const w = M.w + 2 * b * k;
    const h = M.h + b * k;
    const x = (outerW - w) / 2;
    const y = outerH - h;
    shapes.push({ k, x, y, w, h, s: M.sag * (w / M.w) });
  }
  return { b, outerW, outerH, baseY: outerH + M.gap, shapes };
}

const svg = (vb, w, h, body) =>
  `<svg xmlns="http://www.w3.org/2000/svg" viewBox="${vb}" width="${r(w)}" height="${r(h)}" fill="none" color="#eff1ee">\n${body}\n</svg>\n`;

// 1. Nested three levels, the page-end outline. Line weights are CSS px at
//    the given outer width; opacities 22% / 40% / 100% from outer to inner.
const n3 = nested(3);
const pad = 1;
const nestedVb = { w: r(n3.outerW + 2 * pad), h: r(n3.baseY + 2 * pad) };
const nestedPaths = n3.shapes.map((s) => ({
  level: s.k,
  d: block(s.x + pad, s.y + pad, s.w, s.h, s.s),
}));
const nestedBase = `M${pad} ${r(n3.baseY + pad)}H${r(n3.outerW + pad)}`;
const inner = n3.shapes.find((s) => s.k === 0);
{
  const size = 560;
  const k = size / n3.outerW;
  const sw = 1 / k;
  const opacity = { 2: 0.22, 1: 0.4, 0: 1 };
  const body =
    nestedPaths
      .map(
        (p) =>
          `  <path d="${p.d}" stroke="currentColor" stroke-opacity="${opacity[p.level]}" stroke-width="${r(sw)}"/>`,
      )
      .join("\n") +
    `\n  <path d="${nestedBase}" stroke="currentColor" stroke-opacity="0.34" stroke-width="${r(sw)}"/>`;
  writeFileSync(
    join(svgOut, "nested-3.svg"),
    svg(
      `0 0 ${nestedVb.w} ${nestedVb.h}`,
      nestedVb.w * k,
      nestedVb.h * k,
      body,
    ),
  );
}

// 2. FAQ indicator (closed / open): a 10px block, 1px line; open = filled.
const faq = (() => {
  const bw = 10;
  const k = bw / M.w;
  const bh = M.h * k;
  return { w: 11, h: r(bh + 1), d: block(0.5, 0.5, bw, bh, M.sag * k) };
})();
for (const open of [false, true]) {
  const body = `  <path d="${faq.d}" stroke="currentColor" stroke-width="1"${open ? ' fill="currentColor"' : ""}/>`;
  writeFileSync(
    join(svgOut, `faq-indicator-${open ? "open" : "closed"}.svg`),
    svg(`0 0 ${faq.w} ${faq.h}`, faq.w, faq.h, body),
  );
}

// 3. The paths for inline SVG in the page (the page draws them with
//    currentColor so the canvas tokens decide the ink).
const ts = `// Generated by apps/landing/scripts/assets/outline.mjs. Do not edit.
// The mosoo logo outline: the block as a window, the bar as a line.

export const NESTED_VIEWBOX = { width: ${nestedVb.w}, height: ${nestedVb.h} } as const;

/** Outer (level 2) to inner (level 0). */
export const NESTED_PATHS: readonly { level: 0 | 1 | 2; d: string }[] = ${JSON.stringify(nestedPaths)};

export const NESTED_BASE = ${JSON.stringify(nestedBase)};

/** The inner window's box in viewBox units (for the fill inside it). */
export const NESTED_INNER = ${JSON.stringify({ x: r(inner.x + pad), y: r(inner.y + pad), width: r(inner.w), height: r(inner.h) })} as const;

export const FAQ_INDICATOR = ${JSON.stringify(faq)} as const;
`;
writeFileSync(tsOut, ts);
console.log("ok", {
  band: r(n3.b),
  outerW: r(n3.outerW),
  baseY: r(n3.baseY),
  inner: r(inner.w),
});
